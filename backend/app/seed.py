def seed(db):
    if db.scalar(select(func.count(Part.id))):
        raise ValueError("物料库非空，未导入演示数据")
    locations = [
        Location(code=code, name=name, description=desc, capacity=cap, is_demo=True)
        for code, name, desc, cap in [
            ("A-01", "电阻收纳盒", "工作台左侧 · 第一层", 24),
            ("A-02", "电容 / 电感收纳盒", "工作台左侧 · 第二层", 24),
            ("B-01", "集成电路防静电盒", "防静电柜 · 上层", 16),
            ("B-02", "开发模块收纳盒", "防静电柜 · 下层", 12),
            ("C-01", "分立器件收纳盒", "工作台右侧 · 第一层", 24),
            ("C-02", "连接器 / 其他", "工作台右侧 · 第二层", 16),
        ]
    ]
    db.add_all(locations)
    db.flush()
    stamp = now()
    for index, (
        sku,
        name,
        category,
        manufacturer,
        package,
        description,
        qty,
        minimum,
        price,
        loc,
        specs,
    ) in enumerate(SAMPLES):
        part = Part(
            sku=sku,
            name=name,
            category=category,
            manufacturer=manufacturer,
            package=package,
            description=description,
            quantity=qty,
            min_quantity=minimum,
            unit_price=Decimal(price),
            location_id=locations[loc].id,
            specs=specs,
            is_demo=True,
            created_at=stamp - timedelta(minutes=index + 10),
        )
        db.add(part)
        db.flush()
        outgoing = (index % 4 + 1) * (10 if category in ("电阻", "电容") else 1)
        initial = qty + outgoing
        db.add(
            Movement(
                part_id=part.id,
                kind="in",
                quantity=initial,
                balance=initial,
                reason="采购入库 · 演示数据",
                actor="demo",
                is_demo=True,
                created_at=stamp - timedelta(days=(index % 12) + 2),
            )
        )
        db.add(
            Movement(
                part_id=part.id,
                kind="out",
                quantity=outgoing,
                balance=qty,
                reason="项目领料 · 演示数据",
                actor="demo",
                is_demo=True,
                created_at=stamp - timedelta(hours=index * 3 + 1),
            )
        )
    db.commit()


if __name__ == "__main__":
    with SessionLocal() as session:
        seed(session)
        print("已导入 24 种演示物料、6 个库位及相应流水。")
